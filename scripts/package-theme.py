#!/usr/bin/env python3
"""Deterministic source + runtime theme ZIP. Run build/tests first; never pack ignored files or credentials."""
import json
import os
import re
from pathlib import Path, PurePosixPath
import shutil
import struct
import subprocess
import tempfile
import time
import zipfile

root = Path(__file__).resolve().parents[1]
os.chdir(root)
version = json.loads((root / 'package.json').read_text())['version']
package_lock = json.loads((root / 'package-lock.json').read_text())
if package_lock.get('version') != version or package_lock.get('packages', {}).get('', {}).get('version') != version:
    raise SystemExit('package-lock.json root versions must match package.json before packaging.')
manifest = root / 'assets/compiled/manifest.json'
if not manifest.is_file():
    raise SystemExit('Missing build: run npm ci && npm run build first.')
paths = set(subprocess.check_output(['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z']).decode().split('\0'))
screenshot_name = next((name for name in ('screenshot.png', 'screenshot.webp') if (root / name).is_file() and name in paths), None)
epoch = int(os.environ.get('SOURCE_DATE_EPOCH', subprocess.check_output(['git', 'show', '-s', '--format=%ct', 'HEAD']).decode().strip()))
stamp = time.gmtime(max(315532800, epoch))[:6]
destination = root / 'artifacts' / f'zarrin-{version}.zip'
download_destination = root / 'downloads' / f'jluxe-mobile-nav-{version}.zip'
destination.parent.mkdir(exist_ok=True)
download_destination.parent.mkdir(exist_ok=True)
excluded = ('.git/', '.github/', 'node_modules/', 'dist/', 'artifacts/', 'downloads/', '.cache/', 'coverage/', '.arena/', 'tests/', 'src/', 'docs/', 'scripts/')
# Local assistant notes, MU-plugin candidates, test fixtures, and scratch files
# are not part of the installable theme. ZIP inputs and generated bytecode are
# excluded so local build artifacts never leak into a release.
excluded_workspace_files = {
    '.gitignore', 'AGENTS.md', '3.php', '11.php', '3.txt',
    # Imported audit notes and a local UX recording are source-workspace artifacts,
    # never files belonging in the installable WordPress theme.
    'mosh.txt', 'new 1.txt', 'new 2.txt', 'new 3.txt', 'new 4.txt', 'sql.txt',
    'mehrad_ux_20261109_205854270.mp4',
    # Development metadata and the unminified WooCommerce source are not runtime files.
    'package.json', 'package-lock.json', 'assets/js/woocommerce.js', 'logo.png',
}
with zipfile.ZipFile(destination, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for name in sorted(paths):
        parts = Path(name).parts
        if not name or name in excluded_workspace_files or PurePosixPath(name).suffix.lower() in {'.zip', '.pyc', '.pyo'} or '__pycache__' in parts or name.startswith(excluded) or any(part in ('.env', '.git-credentials', '.netrc') or part.startswith('.env.') for part in parts):
            continue
        source = root / name
        if source.is_symlink():
            raise SystemExit(f'Refusing symlink in release: {name}')
        if not source.is_file():
            continue
        info = zipfile.ZipInfo('zarrin/' + name, stamp)
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        archive.writestr(info, source.read_bytes(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)

with zipfile.ZipFile(destination) as archive:
    names = archive.namelist()
    leaked_workspace_files = sorted(f'zarrin/{name}' for name in excluded_workspace_files if f'zarrin/{name}' in names)
    if leaked_workspace_files:
        raise SystemExit('Release contains excluded workspace-only files: ' + ', '.join(leaked_workspace_files))
    required_files = (
        'style.css',
        'functions.php',
        'assets/compiled/manifest.json',
        'assets/compiled/woocommerce.min.js',
        'assets/compiled/woocommerce.product.min.js',
        'assets/compiled/woocommerce.cart-checkout.min.js',
        'inc/data/iran-cities.json',
        'inc/data/iran-cities-GPL-3.0.txt',
        'inc/data/iran-cities-MIT-LICENSE.txt',
    )
    for required in required_files:
        if 'zarrin/' + required not in names:
            raise SystemExit('Release missing runtime file ' + required)
    if not screenshot_name or 'zarrin/' + screenshot_name not in names:
        raise SystemExit('Release must include a root screenshot.png or screenshot.webp for the WordPress theme preview.')
    if screenshot_name == 'screenshot.png':
        preview_header = (root / screenshot_name).read_bytes()[:24]
        if len(preview_header) < 24 or preview_header[:8] != b'\x89PNG\r\n\x1a\n' or struct.unpack('>II', preview_header[16:24]) != (1200, 900):
            raise SystemExit('WordPress screenshot.png must be a valid 1200x900 PNG preview.')
    if 'zarrin/logo.png' in names:
        raise SystemExit('Release contains the unused 267 KB root logo.png; it is not referenced by the theme.')
    if any(name.startswith(('zarrin/src/', 'zarrin/docs/', 'zarrin/scripts/')) for name in names):
        raise SystemExit('Release contains a source, docs, or scripts directory.')
    if any(name in names for name in ('zarrin/package.json', 'zarrin/package-lock.json', 'zarrin/assets/js/woocommerce.js')):
        raise SystemExit('Release contains npm metadata or the unminified WooCommerce source.')
    if any(name.startswith('zarrin/assets/fonts/') for name in names):
        raise SystemExit('Release contains duplicated/unused root-level font assets.')
    required_modules = (
        'inc/homepage/admin-editor.php',
        'inc/homepage/hooks.php',
        'inc/homepage/sections-products.php',
        'inc/homepage/sections-media.php',
        'inc/homepage/sections-catalog.php',
        'inc/woocommerce/pricing-toman.php',
        'inc/woocommerce/product-single.php',
        'inc/woocommerce/checkout-fields.php',
        'inc/woocommerce/catalog-shop.php',
        'inc/woocommerce/admin-product-meta.php',
        'inc/woocommerce/hooks.php',
    )
    for required in required_modules:
        if 'zarrin/' + required not in names:
            raise SystemExit('Release missing refactored module ' + required)
    if any(name.startswith('zarrin/dist/') for name in names):
        raise SystemExit('Release contains the obsolete legacy dist/ build; use assets/compiled/.')
    if any(not name.startswith('zarrin/') for name in names):
        raise SystemExit('Release contains a path outside the zarrin/ theme directory.')
    for name in names:
        path = PurePosixPath(name)
        if path.is_absolute() or '..' in path.parts:
            raise SystemExit('Release contains an unsafe archive path: ' + name)
    corrupt = archive.testzip()
    if corrupt is not None:
        raise SystemExit('Corrupt ZIP member: ' + corrupt)

    # Verify the archive after extraction, not just the in-memory source tree/CRC.
    with tempfile.TemporaryDirectory(prefix='zarrin-zip-verify-') as unpacked:
        archive.extractall(unpacked)
        extracted_theme = Path(unpacked) / 'zarrin'
        if not (extracted_theme / 'assets/compiled/manifest.json').is_file():
            raise SystemExit('Extracted release is missing its Vite manifest.')
        stylesheet = (extracted_theme / 'style.css').read_text()
        extracted_version_match = re.search(r'(?m)^Version:\s*([^\s]+)\s*$', stylesheet)
        if not extracted_version_match or extracted_version_match.group(1) != version:
            raise SystemExit('Extracted style.css version does not match package.json.')
        extracted_manifest = json.loads((extracted_theme / 'assets/compiled/manifest.json').read_text())
        for entry_name, entry in extracted_manifest.items():
            for reference in (*entry.get('imports', []), *entry.get('dynamicImports', [])):
                if reference not in extracted_manifest:
                    raise SystemExit(f'Extracted manifest dependency is missing: {entry_name} -> {reference}')
            for key in ('file', 'css', 'assets'):
                references = entry.get(key, [])
                if isinstance(references, str):
                    references = [references]
                for reference in references:
                    asset_path = PurePosixPath('assets/compiled') / reference
                    if asset_path.is_absolute() or '..' in asset_path.parts or not (extracted_theme / asset_path).is_file():
                        raise SystemExit(f'Extracted manifest reference is missing/unsafe: {entry_name} -> {reference}')
        if (extracted_theme / 'dist').exists():
            raise SystemExit('Extracted release contains dist/; the current runtime bundle is assets/compiled/.')
        if len(names) != len(set(names)):
            raise SystemExit('Release contains duplicate archive paths.')

# Publish the exact validated archive to the download server's watched directory.
# Replace atomically so a concurrent request cannot stream a half-copied ZIP.
# The preview server reads package.json on each request, so no restart is needed.
temporary_download = download_destination.with_name(f'.{download_destination.name}.{os.getpid()}.tmp')
try:
    shutil.copyfile(destination, temporary_download)
    with zipfile.ZipFile(temporary_download) as download_archive:
        if download_archive.testzip() is not None:
            raise SystemExit('The download-server ZIP copy failed CRC verification.')
        download_style = download_archive.read('zarrin/style.css').decode('utf-8')
        download_version_match = re.search(r'(?m)^Version:\s*([^\s]+)\s*$', download_style)
        if not download_version_match or download_version_match.group(1) != version:
            raise SystemExit('The download-server ZIP copy does not match package.json.')
    os.replace(temporary_download, download_destination)
finally:
    temporary_download.unlink(missing_ok=True)

print(f'Release verified: {destination.relative_to(root)} ({len(names)} files; {destination.stat().st_size} bytes; extracted manifest/assets checked)')
print('Theme screenshot included: ' + screenshot_name if screenshot_name else 'Theme screenshot check: no root screenshot.png or screenshot.webp is present.')
print(f'Download server updated: {download_destination.relative_to(root)}')
